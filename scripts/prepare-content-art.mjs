// Import generated art into padded, regular Cocos atlases; no creative repainting.
import sharp from 'sharp';
import {readFile,writeFile} from 'node:fs/promises';
import {randomUUID,createHash} from 'node:crypto';
import {resolve} from 'node:path';
const [front,back,people]=process.argv.slice(2);
if(!front||!back||!people)throw new Error('Usage: node scripts/prepare-content-art.mjs front.png back.png people.png');
const dir=resolve('assets/resources/art');
async function metadata(key,width,height){
 const template=JSON.parse(await readFile(resolve(dir,'orbital-expansion-front.png.meta'),'utf8'));
 const old=template.uuid,id=randomUUID();
 let text=JSON.stringify(template).replaceAll(old,id).replaceAll('orbital-expansion-front',key);
 const value=JSON.parse(text),frame=value.subMetas.f9941.userData;
 Object.assign(frame,{width,height,rawWidth:width,rawHeight:height,offsetX:0,offsetY:0,trimX:0,trimY:0});
 await writeFile(resolve(dir,key+'.png.meta'),JSON.stringify(value,null,2)+'\n');
}
async function pack(source,key,cols,rows,count,cellW,cellH){
 const {data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true}),layers=[];
 // Generated cutouts can contain barely visible alpha noise outside the figure.
 // Normalize that import residue before trim; retain normal antialiased edge pixels.
 for(let i=0;i<data.length;i+=4)if(data[i+3]<16)data.fill(0,i,i+4);
 const input=await sharp(data,{raw:info}).png().toBuffer();
 const rowCuts=Array.from({length:rows+1},(_,i)=>Math.floor(i*info.height/rows));
 if(key==='orbital-people-annex'){
  // The drawing's two rows are not mathematically equal. Find the actual empty
  // horizontal gutter, so an upper tile cannot steal a lower character's crown.
  let least=Infinity,positions=[];
  for(let y=Math.floor(info.height*.4);y<Math.ceil(info.height*.6);y++){
   let pixels=0;for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>=16)pixels++;
   if(pixels<least){least=pixels;positions=[y];}else if(pixels===least)positions.push(y);
  }
  if(least>info.width*.01)throw new Error('Character rows have no safe transparent gutter');
  rowCuts[1]=Math.round(positions.reduce((a,b)=>a+b,0)/positions.length);
  console.log('Character source row boundary:',rowCuts[1]);
 }
 for(let i=0;i<count;i++){
  const x=i%cols,y=Math.floor(i/cols),left=Math.floor(x*info.width/cols),top=rowCuts[y];
  const width=Math.floor((x+1)*info.width/cols)-left,height=rowCuts[y+1]-top;
  const raw=await sharp(input).extract({left,top,width,height}).png().toBuffer();
  const sprite=await sharp(raw).trim({background:'#00000000',threshold:0}).resize(Math.floor(cellW*.84),Math.floor(cellH*.92),{fit:'inside'}).png().toBuffer();
  const size=await sharp(sprite).metadata();
  layers.push({input:sprite,left:x*cellW+Math.floor((cellW-size.width)/2),top:y*cellH+Math.floor((cellH-size.height)/2)});
 }
 const path=resolve(dir,key+'.png');
 await sharp({create:{width:cols*cellW,height:rows*cellH,channels:4,background:'#00000000'}}).composite(layers).png().toFile(path);
 await metadata(key,cols*cellW,rows*cellH);
 console.log(key,cols*cellW,rows*cellH,createHash('sha256').update(await readFile(path)).digest('hex'));
}
await pack(front,'orbital-annex-front',5,5,20,256,256);
await pack(back,'orbital-annex-back',5,5,20,256,256);
await pack(people,'orbital-people-annex',2,2,4,512,768);

// Normalized contact rectangles for the exact same .035 crop used by OrbitalUI.
const result={};
for(const face of ['front','back']){
 const {data,info}=await sharp(resolve(dir,`orbital-annex-${face}.png`)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 for(let i=0;i<20;i++){
  const cell=256,sx=i%5*cell+cell*.035,sy=Math.floor(i/5)*cell+cell*.035,span=cell*.93;
  let minX=Infinity,minY=Infinity,maxX=-1,maxY=-1;
  for(let y=Math.ceil(sy);y<Math.floor(sy+span);y++)for(let x=Math.ceil(sx);x<Math.floor(sx+span);x++)if(data[(y*info.width+x)*4+3]){minX=Math.min(minX,x);minY=Math.min(minY,y);maxX=Math.max(maxX,x);maxY=Math.max(maxY,y);}
  if(maxX<0)throw new Error(`Empty sprite ${i} ${face}`);
  const x=Math.max(0,(minX-sx-1)/span),y=Math.max(0,(minY-sy-1)/span),right=Math.min(1,(maxX-sx+2)/span),bottom=Math.min(1,(maxY-sy+2)/span);
  (result[`ITM-${String(81+i).padStart(3,'0')}`]??={})[face]=[x,y,right-x,bottom-y].map(n=>Number(n.toFixed(9)));
 }
}
await writeFile('assets/scripts/orbital/AnnexBounds.ts',`// Generated by scripts/prepare-content-art.mjs from the shipped PNG alpha.\nexport const ANNEX_BOUNDS=${JSON.stringify(result,null,2)} as const;\n`);
