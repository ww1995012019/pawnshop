    def scale_controls(self):
        self.phase("integrated scale " + ("touch" if self.mobile else "mouse"))
        self.command({"type": "page", "page": "inspect"})
        self.wait("OrbitalTouch.state.workspace==='inspect'")
        self.command({"type": "tool", "tool": "TOL-005"})
