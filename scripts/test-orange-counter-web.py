        self.report.setdefault("scale_geometry", {})[self.prefix] = {"tare": tare, "place": place}
        if self.mobile:
            self.check(tare["height"] >= 43 and place["height"] >= 43, "integrated instrument retains real finger-sized keys", (tare, place))
        else:
            self.check(tare["height"] >= 24 and place["height"] >= 24, "scaled desktop instrument retains usable mouse targets", (tare, place))
        self.check(abs(tare["y"] - place["y"]) < 2 and abs(tare["x"] - place["x"]) < 150, "two real instrument keys occupy the same compact housing row")
        uid = self.state()["inspection_uid"]
        before = self.saved()
        original = next(item for item in before["inventory"] if item["uid"] == uid)
        self.snap("scale-integrated-untared")
        self.click("@scale_tare")
        self.check(not self.locate("@scale_place")["disabled"] and not self.state()["scale_occupied"], "real body TARE enables placement without occupying the scale")
        self.click("@scale_place")
        self.wait("OrbitalTouch.state.scale_occupied")
        self.check(not self.state()["scale_stable"], "real placement waits for stability")
        self.wait("OrbitalTouch.state.scale_stable")
        stable = self.wait_saved(lambda state: "TOL-005" in next(item for item in state["inventory"] if item["uid"] == uid)["evidence"], "stable physical LCD automatically records mass evidence")
        free = original["inspectedPaid"] or before["upgrades"].get("lamp", False)
        self.check(stable["ap"] == before["ap"] - (0 if free else 1), "first physical reading follows the existing AP rule")
        self.snap("scale-integrated-stable-lcd")
        costs, ap = stable.get("storeCosts"), stable["ap"]
        self.click("@scale_tare")
        self.check(not self.state()["scale_occupied"] and self.state()["inspection_uid"] == uid, "occupied TARE clears the same original before zeroing")
        self.click("@scale_place")
        self.wait("OrbitalTouch.state.scale_stable")
        self.page.wait_for_timeout(250)
        repeated = self.saved()
        self.check(repeated["ap"] == ap and repeated.get("storeCosts") == costs, "unchanged repeat mass does not double-charge AP or electricity")
        self.check(sum(item["uid"] == uid for item in repeated["inventory"]) == 1, "instrument never duplicates the original UID")
        self.snap("scale-real-touch-repeat")
        self.close_layers()

