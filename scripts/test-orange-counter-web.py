def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("url", nargs="?", default="http://127.0.0.1:4174/")
    parser.add_argument("--case", choices=("all", "desktop", "desktop-idle", "desktop-trade", "desktop-scale", "dialogue", "portrait-guide", "short-portrait", "phones", "scale", "wanted"), default="all")
    parser.add_argument("--fixtures", type=Path, help="Read an explicit fixture JSON; otherwise generate normal saves with Godot")
    parser.add_argument("--output", type=Path, default=ROOT / "work/orange-counter-tools/browser")
    args = parser.parse_args()
    args.output = args.output.resolve()
    args.fixtures = args.fixtures.resolve() if args.fixtures else prepare_fixtures()
    fixtures = json.loads(args.fixtures.read_text())
    args.output.mkdir(parents=True, exist_ok=True)
    report = {"case": args.case, "checks": [], "screenshots": [], "passed": False}
    active = None
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(executable_path=os.environ.get("CHROMIUM_EXECUTABLE") or shutil.which("chromium"),
                    args=["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--mute-audio"])
        try:
            if args.case in ("all", "desktop", "desktop-idle", "desktop-trade", "desktop-scale", "dialogue"):
                active = Probe(browser, args.output, args.url, (1440, 900), False, report)
                if args.case in ("all", "desktop", "desktop-idle"):
                    for width, height in ((1440, 900), (1160, 700)):
                        active.resize(width, height)
                        active.idle_desktop(fixtures["idle"])
                if args.case in ("all", "desktop", "desktop-trade"):
                    active.resize(1440, 900)
                    active.trade_desktop(fixtures["trade"])
                if args.case == "dialogue":
                    active.dialogue_desktop(fixtures["trade"])
                    active.portrait_action_preview()
                if args.case in ("all", "desktop", "desktop-trade", "desktop-scale"):
                    active.load(fixtures["idle"])
                    active.scale_controls()
                    active.desktop_poster_layer()
                    active.clean_desktop_previews(fixtures["idle"])
                active.finish()
                active = None
            if args.case in ("all", "phones", "scale", "wanted"):
                for size in ((844, 390), (390, 844)):
                    active = Probe(browser, args.output, args.url, size, True, report)
                    active.load(fixtures["idle"])
                    if args.case in ("all", "phones", "scale"):
                        active.scale_controls()
                    if args.case in ("all", "phones", "wanted"):
                        active.wanted_phone(fixtures["idle"])
                    if args.case == "all" and size == (390, 844):
                        active.portrait_action_preview()
                        active.short_portrait_actions()
                    active.finish()
                    active = None
            if args.case == "portrait-guide":
                active = Probe(browser, args.output, args.url, (390, 844), False, report)
                active.load(fixtures["idle"])
                active.portrait_action_preview()
                active.short_portrait_actions()
                active.finish()
                active = None
            if args.case == "short-portrait":
                active = Probe(browser, args.output, args.url, (390, 640), False, report)
                active.load(fixtures["idle"])
                active.command({"type": "page", "page": "inspect"})
                active.wait("OrbitalTouch.state.workspace==='inspect'")
                active.command({"type": "tool", "tool": "TOL-005"})
                active.wait("OrbitalTouch.state.inspection_current==='TOL-005'&&!OrbitalTouch.state.inspection_busy")
                active.short_portrait_actions()
                active.finish()
                active = None
            report["passed"] = True
        except Exception as error:
            report["failure"] = str(error)
            if active is not None:
                active.failure()
            raise
        finally:
            browser.close()
            (args.output / "results.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(f"ORANGE BROWSER {len(report['checks'])} checks passed; screenshots: {args.output}", flush=True)


if __name__ == "__main__":
    main()
