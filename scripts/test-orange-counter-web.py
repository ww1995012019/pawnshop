    def short_portrait_actions(self):
        self.resize(390, 640)
        self.phase("short portrait local paper scrolling")
        self.page.wait_for_timeout(350)
        # WebTouch intentionally locates Buttons, not ScrollContainers. Use the
        # real picker and paper-frame hits to locate their native scroll area.
        guide = self.locate("@watch_manual")
        picker = self.locate(self.state()["detail_title"])
        state = self.state()
        mat, frame = state["inspection_mat"], state["workspace_rect"]
        scale = guide["height"] / 44
        picker_box = corners(picker)
        detail_bottom = frame["y"] + frame["height"] - 22 * scale
        details = {"x": picker_box[2] + 5 * scale, "y": (picker_box[1] + detail_bottom) / 2,
                   "width": picker["width"] + 12 * scale, "height": detail_bottom - picker_box[1]}
        instruction_top = mat["y"] + mat["height"] + 16 * scale
        instruction_bottom = picker_box[1] - 24 * scale
        instructions = {"x": mat["x"] + mat["width"] / 2, "y": (instruction_top + instruction_bottom) / 2,
                        "width": mat["width"] - 16 * scale, "height": instruction_bottom - instruction_top}
        self.report["short_portrait_geometry"] = {"picker": picker, "frame": frame, "instructions": instructions, "details": details}
        self.check(corners(details)[3] <= self.height - 35 and details["height"] >= 52,
                   "short portrait details occupy their actual visible viewport", details)
        self.check(corners(instructions)[3] + 4 <= corners(details)[1],
                   "short portrait explanation and actions have separate local scroll surfaces", (instructions, details))
        self.page.mouse.move(instructions["x"], instructions["y"])
        before = self.snap("portrait-short-instructions-top")
        self.page.mouse.wheel(0, 700)
        self.page.wait_for_timeout(250)
        after = self.snap("portrait-short-instructions-scrolled")
        box = tuple(round(value * self.dpr) for value in corners(instructions))
        self.check(changed_pixels(before.crop(box), after.crop(box)) > 50,
                   "real wheel input reveals the full unchanged electricity explanation")
        self.page.mouse.move(details["x"], details["y"])
        self.page.mouse.wheel(0, 900)
        self.page.wait_for_timeout(250)
        repair = self.locate("去维修")
        a, b = (picker_box[0], picker_box[1], picker_box[2], detail_bottom), corners(repair)
        visible = max(a[0], b[0]), max(a[1], b[1]), min(a[2], b[2]), min(a[3], b[3])
        self.check(visible[2] > visible[0] and visible[3] - visible[1] >= 40,
                   "scrolling reveals a complete usable final repair action", (details, repair, visible))
        self.page.mouse.move(2, 2)
        self.snap("portrait-short-final-action-visible")
        self.page.mouse.click((visible[0] + visible[2]) / 2, (visible[1] + visible[3]) / 2)
        self.wait("OrbitalTouch.state.workspace==='repair'")
        self.check(True, "real click on the scrolled final action opens repair")
        self.snap("portrait-short-final-action-real-open")

    def trade_desktop(self, fixture):
        self.dialogue_desktop(fixture)
        shop_uid, npc_uid = fixture["shop_uid"], fixture["npc_uid"]
        self.hover_pixels("@QuickCheckout", "main-checkout")
        self.check(self.state()["trade"], "pressed checkout feedback never accidentally submits")
        project, sx, sy, origin = self.map_counter(shop_uid)
        extra_x = self.width / sx - 1671
        a = project(474 + extra_x / 2, 94)
        b = project(857 + extra_x / 2, 456)
        self.page.mouse.move(self.width - 2, 2)
        first = self.snap("visitor-baseline-a")
        self.page.wait_for_timeout(450)
        second = self.snap("visitor-baseline-b")
        area = tuple(round(value * self.dpr) for value in (*a, *b))
        drift = changed_pixels(first.crop(area), second.crop(area), 12)
        self.check(drift < max(12, (b[0] - a[0]) * (b[1] - a[1]) * .003), "standing painted visitor has no full-image vertical drift", drift)
        self.phase("reject NPC original stock drop")
        before = self.saved()
        npc = self.locate("@strict_table_" + npc_uid)
        baseline = self.snap("before-npc-stock-rejection")
        self.drag((npc["x"], npc["y"]), project(30, 610), "npc-stock-rejection")
        refused = self.snap("npc-stock-red-reason")
        after = self.saved()
        self.check(not any(item["uid"] == npc_uid for item in after["inventory"]), "NPC original cannot enter shop inventory")
        self.check(any(row["uid"] == npc_uid for row in self.state()["table_items"]), "rejected NPC original stays on its original table")
        self.check(after["cash"] == before["cash"] and after["ap"] == before["ap"], "rejected NPC drop spends no cash or AP")
        old_red = [r > g * 1.35 and r > b * 1.25 and r > 80 for r, g, b in baseline.get_flattened_data()]
        red = sum(r > g * 1.35 and r > b * 1.25 and r > 80 and not old for (r, g, b), old in zip(refused.get_flattened_data(), old_red))
        self.check(red > 150, "NPC refusal presents a visibly brick-red reason banner", red)
        self.phase("withdraw shop display original from current sale")
        original = next(item for item in before["inventory"] if item["uid"] == shop_uid)
        key = self.locate("@strict_table_" + shop_uid)
        self.drag((key["x"], key["y"]), project(30, 610), "trade-shop-return")
        after = self.wait_saved(lambda state: any(item["uid"] == shop_uid and item["location"] == "warehouse" for item in state["inventory"]),
                                "trade shop original returns from display to warehouse")
        line = next(row for row in after["trade"]["session"]["lines"] if row["uid"] == shop_uid)
        self.check(not line["included"] and not line["selected"], "returned shop original is excluded from pending settlement")
        self.check(not any(row["uid"] == shop_uid for row in self.state()["table_items"]), "returned shop original has no stale table target")
        stored = next(item for item in after["inventory"] if item["uid"] == shop_uid)
        self.check(original_facts(stored) == original_facts(original), "trade withdrawal preserves original facts")
        selected = [row for row in after["trade"]["session"]["lines"] if row.get("included") and row.get("selected") and row["status"] == "confirmed"]
        self.check(all(row["uid"] != shop_uid for row in selected) and any(row["uid"] == npc_uid for row in selected), "checkout contains only still-selected originals")
        expected_cash = after["cash"] + self.state()["trade_session"]["net"]
        ap = after["ap"]
        self.click("@QuickCheckout")
        checked = self.wait_saved(lambda state: any(item["uid"] == npc_uid for item in state["inventory"]), "real checkout acquires the confirmed NPC original")
        self.check(checked["cash"] == expected_cash and checked["ap"] == ap - 1, "real remaining checkout settles once with one AP")
        self.check(next(item for item in checked["inventory"] if item["uid"] == shop_uid)["location"] == "warehouse", "checkout leaves the withdrawn shop original in inventory")
