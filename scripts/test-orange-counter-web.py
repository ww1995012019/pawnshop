def module(name, relative):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded


service = module("orange_service", "scripts/test-watch-service-web.py")
warehouse = module("orange_warehouse", "scripts/test-warehouse-expansion-web.py")


def prepare_fixtures():
    """Generate ordinary saves with the real reducers, outside the export tree."""
    with tempfile.TemporaryDirectory(prefix="orange-counter-fixtures-") as saves:
        result = subprocess.run([os.environ.get("GODOT_BIN", "godot"), "--headless", "--path", str(ROOT / "godot"),
                                 "--script", str(ROOT / "scripts/orange-counter-fixture.gd")],
                                env={**os.environ, "XDG_DATA_HOME": saves}, capture_output=True, text=True, timeout=60)
        if result.returncode or "SCRIPT ERROR" in result.stdout + result.stderr:
            raise RuntimeError(result.stdout + result.stderr)
    return ROOT / "work/orange-counter-tools/browser-fixtures.json"


def corners(hit):
    return (hit["x"] - hit["width"] / 2, hit["y"] - hit["height"] / 2,
            hit["x"] + hit["width"] / 2, hit["y"] + hit["height"] / 2)


def changed_pixels(a, b, threshold=8):
    return sum(max(pixel) > threshold for pixel in ImageChops.difference(a, b).get_flattened_data())


def original_facts(item):
    return {key: value for key, value in item.items() if key not in ("location", "x", "y", "rotated")}


class Probe:
    def __init__(self, browser, output, url, size, mobile, report):
        self.width, self.height = size
        self.mobile, self.dpr = mobile, 2 if mobile else 1
        self.output, self.url, self.report = output, url.rstrip("/") + "/", report
        self.context = browser.new_context(viewport={"width": self.width, "height": self.height},
                                          device_scale_factor=self.dpr, has_touch=mobile, is_mobile=mobile)
        self.page = self.context.new_page()
        self.errors, self.key, self.stage, self.sequence = [], None, "boot", 0
        self.page.on("pageerror", lambda error: self.errors.append(str(error)))
        self.page.on("console", self.console)

    def console(self, message):
        if any(marker in message.text for marker in ("SCRIPT ERROR", "SHADER ERROR", "Error compiling shader")):
            self.errors.append(message.text)

    @property
    def prefix(self):
        return f"{self.width}x{self.height}"

    def phase(self, name):
        self.stage = name
        print(self.prefix + " " + name, flush=True)

    def command(self, data):
        self.page.evaluate("data=>orbitalTouchSend(JSON.stringify(data))", data)

    def state(self):
        return self.page.evaluate("OrbitalTouch.state")

    def snap(self, name):
        self.sequence += 1
        path = self.output / f"{self.prefix}-{self.sequence:02d}-{name}.png"
        rendered = Image.open(io.BytesIO(self.page.screenshot(path=str(path)))).convert("RGB")
        self.report["screenshots"].append(str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path))
        return rendered

    def failure(self):
        try:
            self.snap("failure-" + self.stage.replace(" ", "-"))
            row = {"stage": self.stage, "state": self.state(), "errors": self.errors,
                   "document": self.page.evaluate("({hidden:document.hidden,fullscreen:!!document.fullscreenElement,width:innerWidth,height:innerHeight})")}
            (self.output / f"{self.prefix}-failure.json").write_text(json.dumps(row, ensure_ascii=False, indent=2))
        except Exception as error:
            print("Failure capture:", error, flush=True)

    def check(self, condition, caption, detail=None):
        if not condition:
            raise AssertionError((self.prefix, self.stage, caption, detail))
        self.report["checks"].append({"view": self.prefix, "caption": caption})
        print("PASS " + self.prefix + " " + caption, flush=True)

    def wait(self, expression, timeout=20000, arg=None):
        self.page.wait_for_function(expression, timeout=timeout, arg=arg)

    def locate(self, label, required=True):
        self.page.evaluate("text=>{window.__orbitalLocated=null;orbitalTouchSend(JSON.stringify({type:'locate',text}));}", label)
        self.wait("window.__orbitalLocated!==null")
        hit = self.page.evaluate("window.__orbitalLocated")
        if required:
            self.check(hit["found"], "visible control " + label, hit)
        return hit

    def click(self, label, button="left"):
        hit = self.locate(label)
        self.check(not hit.get("disabled"), "enabled control " + label, hit)
        self.check(0 <= hit["x"] <= self.width and 0 <= hit["y"] <= self.height,
                   "control is inside viewport " + label, hit)
        if self.mobile and button == "left":
            self.page.touchscreen.tap(hit["x"], hit["y"])
        else:
            self.page.mouse.click(hit["x"], hit["y"], button=button)
        self.page.wait_for_timeout(300)
        return hit

    def saved(self):
        row = self.page.evaluate(service.READ_SAVE)
        return row["state"] if row else None

    def wait_saved(self, predicate, caption):
        deadline = time.monotonic() + 15
        while time.monotonic() < deadline:
            state = self.saved()
            if state and predicate(state):
                self.check(True, caption)
                return state
            self.page.wait_for_timeout(150)
        raise AssertionError((caption, self.state(), self.saved()))

    def boot(self):
        self.page.goto(self.url)
        self.wait("window.OrbitalTouch?.state?.ready", timeout=120000)
        self.command({"type": "start"})
        self.wait("!OrbitalTouch.state.title&&!OrbitalTouch.state.busy", timeout=30000)

    def load(self, fixture):
        self.phase("load fixture")
        if self.key is None:
            self.boot()
            if not self.state()["has_save"]:
                self.command({"type": "arrive"})
                self.wait("OrbitalTouch.state.has_save&&!OrbitalTouch.state.busy", timeout=30000)
            row = self.page.evaluate(service.READ_SAVE)
            self.check(bool(row), "fixture save has a real userfs key")
            self.key = row["key"]
        self.page.goto(self.url + "godot-license.txt")
        self.page.evaluate(warehouse.WRITE, {"key": self.key, "state": fixture["state"]})
        self.boot()
        if self.mobile:
            self.page.touchscreen.tap(2, self.height - 2)
        self.page.wait_for_timeout(800)
        self.wait("!OrbitalTouch.state.busy&&!OrbitalTouch.state.blocked")

    def resize(self, width, height):
        self.width, self.height = width, height
        self.page.set_viewport_size({"width": width, "height": height})
        self.page.wait_for_timeout(500)

    def close_layers(self):
        for attempt in range(8):
            state = self.state()
            if not state["workspace"] and not state["blocked"]:
                return
            self.command({"type": "close"})
            self.page.wait_for_timeout(350)
        raise AssertionError(("layers did not close", self.state()))

    def drag(self, source, destination, name):
        sx, sy = source
        tx, ty = destination
        self.page.mouse.move(sx, sy)
        self.page.mouse.down()
        self.page.mouse.move(sx + 12, sy + 3, steps=3)
        for index in range(1, 13):
            self.page.mouse.move(sx + (tx - sx) * index / 12, sy + (ty - sy) * index / 12)
            self.page.wait_for_timeout(25)
        self.snap(name + "-held")
        self.page.mouse.up()
        self.page.wait_for_timeout(450)

    def touch_scroll(self):
        client = self.context.new_cdp_session(self.page)
        x, start_y, end_y = self.width * .52, self.height * .81, self.height * .30
        for swipe in range(8):
            client.send("Input.dispatchTouchEvent", {"type": "touchStart", "touchPoints": [{"x": x, "y": start_y, "id": 0}]})
            for step in range(1, 8):
                client.send("Input.dispatchTouchEvent", {"type": "touchMove", "touchPoints": [{"x": x, "y": start_y + (end_y - start_y) * step / 7, "id": 0}]})
                self.page.wait_for_timeout(35)
            client.send("Input.dispatchTouchEvent", {"type": "touchEnd", "touchPoints": []})
            self.page.wait_for_timeout(170)
        client.detach()

    def hover_pixels(self, label, name):
        self.phase("feedback " + name)
        before_economy = self.state()["cash"], self.state()["ap"]
        self.page.mouse.move(self.width - 2, 2)
        self.page.wait_for_timeout(180)
        hit = self.locate(label)
        self.check(not hit.get("disabled"), name + " is enabled for feedback")
        base = self.snap(name + "-normal")
        self.page.mouse.move(hit["x"], hit["y"])
        self.page.wait_for_timeout(150)
        hover = self.snap(name + "-hover")
        hovered_hit = self.locate(label)
        self.page.mouse.down()
        self.page.wait_for_timeout(130)
        pressed = self.snap(name + "-pressed")
        pressed_hit = self.locate(label)
        self.page.mouse.move(self.width - 2, 2, steps=2)
        self.page.mouse.up()
        self.page.wait_for_timeout(200)
        crop = tuple(round(value * self.dpr) for value in corners(hit))
        normal_crop, hover_crop, pressed_crop = [image.crop(crop) for image in (base, hover, pressed)]
        minimum = max(8, normal_crop.width * normal_crop.height * .004)
        hover_changed = changed_pixels(normal_crop, hover_crop)
        press_changed = changed_pixels(hover_crop, pressed_crop)
        self.check(hover_changed > minimum, name + " hover changes rendered pixels", hover_changed)
        self.check(press_changed > minimum, name + " pressed differs from hover pixels", press_changed)
        self.check(all(abs(hit[key] - other[key]) < .6 for other in (hovered_hit, pressed_hit)
                       for key in ("x", "y", "width", "height")), name + " feedback leaves hit geometry unchanged")
        self.check((self.state()["cash"], self.state()["ap"]) == before_economy, name + " pressed-state capture does not perform an economic action")

    def map_counter(self, first_display_uid):
        key = self.locate("@strict_stock_" + first_display_uid)
        left, top, _, _ = corners(key)
        sx, sy = key["width"] / 90, key["height"] / 130
        origin = (left - 37 * sx, top - 159 * sy)
        return lambda x, y: (origin[0] + x * sx, origin[1] + y * sy), sx, sy, origin

    def orange_menu(self, warehouse_uid, clean=False):
        self.phase("warm orange context menu")
        self.command({"type": "page", "page": "warehouse"})
        self.wait("OrbitalTouch.state.workspace==='warehouse'")
        self.page.wait_for_timeout(300)
        self.wait("uid=>OrbitalTouch.state.warehouse_targets.some(row=>row.uid===uid)", arg=warehouse_uid)
        row = next(row for row in self.state()["warehouse_targets"] if row["uid"] == warehouse_uid)
        self.page.mouse.click(row["x"] + row["width"] / 2, row["y"] + row["height"] / 2, button="right")
        self.page.wait_for_timeout(180)
        hit = self.locate("去鉴定")
        if clean:
            self.page.mouse.move(2, 2)
            self.page.wait_for_timeout(5200)
        rendered = self.snap("orange-watch-menu-clean" if clean else "orange-watch-menu")
        crop = rendered.crop(tuple(round(value * self.dpr) for value in corners(hit)))
        warm = sum(r > g and g > b + 8 and r > b + 20 for r, g, b in crop.get_flattened_data())
        self.check(warm > crop.width * crop.height * .20, "context menu renders warm orange/apricot instead of teal", warm)
        self.page.keyboard.press("Escape")
        self.page.wait_for_timeout(150)
        self.close_layers()

    def idle_desktop(self, fixture):
        self.load(fixture)
        self.phase("idle display and desk document")
        display, stock = fixture["display_uids"], fixture["warehouse_uids"]
        before = self.saved()
        self.check(len(before["inventory"]) == len(display) + len(stock), "wanted document is separate from watch inventory")
        self.check(not self.locate("@strict_wanted_inventory", False)["found"], "wanted document is absent from the watch stock grid")
        self.locate("@wanted_desk_paper")
        self.snap("desk-document-and-five-watches")
        self.click("@wanted_desk_paper")
        self.locate("@wanted_close")
        self.snap("desktop-wanted-poster")
        self.click("@wanted_close")
        self.wait("!OrbitalTouch.state.notice_visible")
        self.orange_menu(stock[0])
        for label, name in [("@StrictNav_box-archive", "navigation"), ("@StrictOrders", "orders"),
                            ("@StrictPeople", "people"), ("@strict_stock_" + stock[1], "stock-watch")]:
            self.hover_pixels(label, name)
        self.page.wait_for_timeout(350)
        self.phase("sixth shelf real drop")
        sixth = self.locate("@strict_empty_display_5")
        second_row = self.locate("@strict_stock_" + display[3])
        first_row = self.locate("@strict_stock_" + display[2])
        self.check(abs(sixth["y"] - second_row["y"]) < 2 and sixth["x"] > second_row["x"] + second_row["width"],
                   "sixth display drop target shares second shelf and third column", (sixth, second_row))
        self.check(sixth["y"] > first_row["y"] + first_row["height"] * .8, "sixth target is below the first shelf")
        source = self.locate("@strict_stock_" + stock[0])
        self.drag((source["x"], source["y"]), (sixth["x"], sixth["y"]), "sixth-shelf")
        self.wait_saved(lambda state: state["showroomLayout"]["display"].get(stock[0]) == 5,
                        "real sixth-shelf drop persists the same UID in slot 5")
        self.snap("six-watches-two-shelves")
        project, _, _, _ = self.map_counter(display[0])
        for uid, destination, name in [(display[0], project(30, 610), "stock-header-return"),
                                       (display[1], None, "stock-child-return")]:
            self.phase(name)
            original = next(item for item in self.saved()["inventory"] if item["uid"] == uid)
            self.click("@strict_stock_" + uid)
            self.wait("OrbitalTouch.state.workspace===''")
            target = self.locate("@strict_table_" + uid)
            if destination is None:
                child = self.locate("@strict_stock_" + stock[1])
                destination = child["x"], child["y"]
            self.drag((target["x"], target["y"]), destination, name)
            after = self.wait_saved(lambda state: any(item["uid"] == uid and item["location"] == "warehouse" for item in state["inventory"]),
                                    name + " unlists the same original through the whole inventory frame")
            stored = [item for item in after["inventory"] if item["uid"] == uid]
            self.check(len(stored) == 1 and original_facts(stored[0]) == original_facts(original), name + " preserves UID, source, price and evidence")
            self.check(after["cash"] == before["cash"] and after["ap"] == before["ap"], name + " spends no cash or AP")
            self.snap(name + "-stored")
        self.phase("reload stored originals")
        self.boot()
        reloaded = self.saved()
        self.check(all(next(item for item in reloaded["inventory"] if item["uid"] == uid)["location"] == "warehouse" for uid in display[:2]),
                   "both whole-frame returns survive a real page reload")
        self.snap("stored-originals-after-reload")

