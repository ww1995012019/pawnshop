    overlay.addComponent<BlockInputEvents>(BlockInputEvents);
    const surface=this.texturePanel(overlay,(1600-width)/2,(900-height)/2,width,height,{name:'modal-surface',skin:'socket'});
    // Brass title plate riveted over the casing, as on a physical instrument.
    const phone=this.phone&&width>=1500,head=phone?128:86;
    const plateW=Math.min(width-(phone?200:140),Math.max(220,title.length*(phone?40:28)+76));
