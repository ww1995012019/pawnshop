#!/usr/bin/env python3
"""Rebuild the active watch game artwork without regenerating removed goods.

Requires Pillow. Original shop/resident masters remain in art-source/shop-v3;
watch artwork and logo data are generated by scripts/generate-watch-art.py.
"""
from pathlib import Path
import subprocess
import sys
from prepare_shop_art import main as prepare_shop_art
from prepare_extra_residents import main as prepare_extra_residents

ROOT = Path(__file__).resolve().parents[2]


def main():
    prepare_shop_art()
    prepare_extra_residents()
    subprocess.run([sys.executable, str(ROOT / "scripts/generate-watch-art.py")], check=True)
    print("Active watch game artwork ready")


if __name__ == "__main__":
    main()
